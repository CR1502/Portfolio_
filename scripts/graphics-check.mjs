import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {mkdir,writeFile} from 'node:fs/promises';
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1280,height:800}});
const errors=[];page.on('pageerror',error=>errors.push(String(error)));
await page.goto(process.env.BASE_URL||'http://localhost:3210',{waitUntil:'networkidle'});
const field=page.locator('.interactive-field');
const snapshot=()=>field.evaluate(el=>el.toDataURL());
const initial=await snapshot();
await page.mouse.move(600,300);await page.waitForTimeout(200);
assert.equal(await snapshot(),initial,'Background must not depend on hover');
await page.evaluate(()=>window.scrollTo({top:650,behavior:'instant'}));await page.waitForTimeout(200);
const scrolled=await snapshot();assert.notEqual(scrolled,initial);
await page.waitForTimeout(400);assert.equal(await snapshot(),scrolled,'Background settles when scrolling stops');
assert.equal(await page.locator('.neural-model,.neural-stage,.chrome-object').count(),0);
assert.equal(await page.locator('.project-visual svg').count(),6);
console.log('✓ scroll-driven contours, no hover response, no idle animation');
await page.emulateMedia({reducedMotion:'reduce'});await page.waitForTimeout(150);
const quiet=await snapshot();await page.evaluate(()=>window.scrollTo({top:1100,behavior:'instant'}));await page.waitForTimeout(150);
assert.equal(await snapshot(),quiet,'Reduced motion keeps field static');
assert.equal(await field.evaluate(el=>getComputedStyle(el).display),'none');
console.log('✓ reduced motion keeps the field static and hides parallax');
assert.deepEqual(errors,[]);
await mkdir('.audit',{recursive:true});
await writeFile('.audit/graphics.json',JSON.stringify({scrollDriven:true,pointerIndependent:true,settles:true,reducedMotion:true,errors},null,2));
await browser.close();
